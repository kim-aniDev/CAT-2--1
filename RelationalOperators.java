public class RelationalOperators {
    public static void main(String[] args) {
        int catMark = 65;
        int passMark = 50;

        System.out.println("catMark == passMark: " + (catMark == passMark));
        System.out.println("catMark != passMark: " + (catMark != passMark));
        System.out.println("catMark > passMark: " + (catMark > passMark));
        System.out.println("catMark < passMark: " + (catMark < passMark));
        System.out.println("catMark >= passMark: " + (catMark >= passMark));
        System.out.println("catMark <= passMark: " + (catMark <= passMark));
    }
}
